#include "planet.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <errno.h>
#include <limits.h>
#include <zlib.h>
typedef struct {
    DVec3 vertex;
    LandscapeSample state;
    double base, ground;
} Sample;
static bool real(const char *text, double *out) {
    char *end;
    errno = 0;
    double n = strtod(text, &end);
    if (errno || !*text || *end || !isfinite(n))
        return false;
    *out = n;
    return true;
}
static bool integer(const char *text, unsigned long *out) {
    char *end;
    errno = 0;
    unsigned long n = strtoul(text, &end, 10);
    if (errno || !*text || *text == '-' || *end)
        return false;
    *out = n;
    return true;
}
static double generated(const LandscapeConfig *c, BiomeId biome, DVec3 point, double amplitude) {
    return landscape_generate_height(c, biome, point, amplitude);
}
static FILE *output(const char *prefix, const char *extension, char path[2048]) {
    int n = snprintf(path, 2048, "%s.%s", prefix, extension);
    return n > 0 && n < 2048 ? fopen(path, "wb") : NULL;
}
static bool export_mesh(const char *prefix, const Sample *samples, unsigned size) {
    char path[2048];
    FILE *f = output(prefix, "ply", path);
    if (!f)
        return false;
    fprintf(f,
            "ply\nformat ascii 1.0\ncomment Generated by voxel-engine landscape tool; local meters\n"
            "element vertex %u\nproperty double x\nproperty double y\nproperty double z\n"
            "property uchar red\nproperty uchar green\nproperty uchar blue\n"
            "element face %u\nproperty list uchar int vertex_indices\nend_header\n",
            size * size, 2 * (size - 1) * (size - 1));
    for (size_t i = 0; i < (size_t)size * size; i++) {
        const Sample *s = &samples[i];
        const Material *m = material_get(s->state.appearance_material);
        fprintf(f, "%.9f %.9f %.9f %u %u %u\n", s->vertex.x, s->vertex.y, s->vertex.z,
                (unsigned)lround(m->color[0] * 255), (unsigned)lround(m->color[1] * 255),
                (unsigned)lround(m->color[2] * 255));
    }
    for (unsigned z = 0; z + 1 < size; z++)
        for (unsigned x = 0; x + 1 < size; x++) {
            unsigned a = z * size + x, b = a + 1, c = a + size, d = c + 1;
            fprintf(f, "3 %u %u %u\n3 %u %u %u\n", a, c, b, b, c, d);
        }
    bool ok = !ferror(f);
    if (fclose(f))
        ok = false;
    return ok;
}
static bool export_samples(const char *prefix, const Sample *samples, unsigned size) {
    char path[2048];
    FILE *f = output(prefix, "csv", path);
    if (!f)
        return false;
    fputs("x_m,y_m,z_m,base_height_m,ground_height_m,source_spacing_m,biome,surface_id,subsoil_id,bedrock_id,"
          "appearance_id,temperature_k,estimated_rain_mm_year,measured_cover\n",
          f);
    for (size_t i = 0; i < (size_t)size * size; i++) {
        const Sample *s = &samples[i];
        const LandscapeSample *b = &s->state;
        fprintf(f, "%.9f,%.9f,%.9f,%.9f,%.9f,%.6f,%s,%u,%u,%u,%u,%.6f,%.6f,%u\n", s->vertex.x, s->vertex.y,
                s->vertex.z, s->base, s->ground, b->source_spacing_m, biome_name(b->biome),
                b->surface_material, b->subsoil_material, b->bedrock_material, b->appearance_material,
                b->temperature_k, b->precipitation_mm, b->measured_cover);
    }
    bool ok = !ferror(f);
    if (fclose(f))
        ok = false;
    return ok;
}
static bool export_image(const char *prefix, const Sample *samples, unsigned size) {
    char path[2048];
    FILE *f = output(prefix, "ppm", path);
    if (!f)
        return false;
    fprintf(f, "P6\n%u %u\n255\n", size, size);
    /* Colour/shadow is extrapolated from the generated height and material,
       with no photographic texture or external bitmap. */
    for (unsigned z = 0; z < size; z++)
        for (unsigned x = 0; x < size; x++) {
            const Sample *s = &samples[(size_t)z * size + x];
            const Sample *west = &samples[(size_t)z * size + (x ? x - 1 : x)],
                         *east = &samples[(size_t)z * size + (x + 1 < size ? x + 1 : x)],
                         *south = &samples[(size_t)(z ? z - 1 : z) * size + x],
                         *north = &samples[(size_t)(z + 1 < size ? z + 1 : z) * size + x];
            double dx = fmax(.000001, fabs(east->vertex.x - west->vertex.x)),
                   dz = fmax(.000001, fabs(north->vertex.z - south->vertex.z));
            DVec3 n = pd_normalize(
                dv3(-(east->vertex.y - west->vertex.y) / dx, 1, -(north->vertex.y - south->vertex.y) / dz));
            double light = .35 + .65 * fmax(0, pd_dot(n, pd_normalize(dv3(-.5, 1, -.3))));
            const Material *m = material_get(s->state.appearance_material);
            unsigned char pixel[3];
            for (int c = 0; c < 3; c++)
                pixel[c] = (unsigned char)lround(fmin(255, m->color[c] * 255 * light));
            fwrite(pixel, 1, 3, f);
        }
    bool ok = !ferror(f);
    if (fclose(f))
        ok = false;
    return ok;
}
int main(int argc, char **argv) {
    LandscapeConfig config = landscape_default();
    unsigned long size = 129, spacing_mm = 8000;
    double amplitude = 1200, latitude = 40, longitude = -105;
    BiomeId biome = BIOME_ALPINE;
    const char *prefix = "landscape", *earth_data = NULL;
    for (int i = 1; i < argc; i++) {
        const char *arg = argv[i];
        if (!strcmp(arg, "--help")) {
            puts("Usage: landscape_generate [--biome NAME] [--seed N] [--size 2..1025] [--spacing-mm N]\n"
                 "  [--amplitude 0..10000] [--roughness 0..4] [--moisture 0..4] [--temperature-offset K]\n"
                 "  [--output PREFIX] [--earth-data FILE --lat DEG --lon DEG]\n"
                 "Writes inspectable CSV, a coloured PLY mesh, PPM overview and JSON metadata.\n"
                 "Default mode generates synthetic landscapes. Earth mode uses actual engine sources/rules.");
            for (int b = 0; b < BIOME_COUNT; b++)
                printf("%s%s", biome_name((BiomeId)b), b + 1 < BIOME_COUNT ? ", " : "\n");
            return 0;
        }
        if (i + 1 >= argc)
            goto invalid;
        const char *value = argv[++i];
        unsigned long n;
        if (!strcmp(arg, "--biome")) {
            biome = biome_find(value);
            if (biome == BIOME_AUTO)
                goto invalid;
        } else if (!strcmp(arg, "--seed")) {
            if (!integer(value, &n) || n > UINT32_MAX)
                goto invalid;
            config.seed = (uint32_t)n;
        } else if (!strcmp(arg, "--size")) {
            if (!integer(value, &size) || size < 2 || size > 1025)
                goto invalid;
        } else if (!strcmp(arg, "--spacing-mm")) {
            if (!integer(value, &spacing_mm) || spacing_mm < 1 || spacing_mm > 1000000)
                goto invalid;
        } else if (!strcmp(arg, "--amplitude")) {
            if (!real(value, &amplitude) || amplitude < 0 || amplitude > 10000)
                goto invalid;
        } else if (!strcmp(arg, "--roughness")) {
            if (!real(value, &config.roughness_scale))
                goto invalid;
        } else if (!strcmp(arg, "--moisture")) {
            if (!real(value, &config.moisture_scale))
                goto invalid;
        } else if (!strcmp(arg, "--temperature-offset")) {
            if (!real(value, &config.temperature_offset_k))
                goto invalid;
        } else if (!strcmp(arg, "--lat")) {
            if (!real(value, &latitude) || fabs(latitude) > 90)
                goto invalid;
        } else if (!strcmp(arg, "--lon")) {
            if (!real(value, &longitude))
                goto invalid;
            longitude = remainder(longitude, 360);
        } else if (!strcmp(arg, "--output"))
            prefix = value;
        else if (!strcmp(arg, "--earth-data"))
            earth_data = value;
        else
            goto invalid;
    }
    if (!landscape_config_valid(&config))
        goto invalid;
    Planet planet = {0};
    if (earth_data &&
        !planet_init(&planet, earth_data, ":memory:", EARTH_MASS_KG, EARTH_A_METERS, EARTH_B_METERS)) {
        fprintf(stderr, "Terrain source: %s\n", planet.error);
        planet_destroy(&planet);
        return 1;
    }
    if (earth_data && (config.seed != landscape_default().seed || config.roughness_scale != 1 ||
                       config.moisture_scale != 1 || config.temperature_offset_k != 0)) {
        fputs("Earth mode uses the engine's saved terrain recipe; generation overrides apply in synthetic "
              "mode.\n",
              stderr);
        planet_destroy(&planet);
        return 1;
    }
    size_t count = (size_t)size * size;
    Sample *samples = calloc(count, sizeof(*samples));
    if (!samples) {
        planet_destroy(&planet);
        return 1;
    }
    double step = spacing_mm * .001, extent = (size - 1) * step;
    DVec3 origin = dv3(0, 0, 0), east = dv3(1, 0, 0), up = dv3(0, 1, 0), north = dv3(0, 0, 1);
    if (earth_data) {
        origin = planet_from_geographic(&planet, latitude, longitude,
                                        planet_visible_elevation(&planet, latitude, longitude));
        up = planet_up(&planet, origin);
        double lon = longitude * 3.14159265358979323846 / 180;
        east = dv3(-sin(lon), cos(lon), 0);
        north =
            dv3(up.y * east.z - up.z * east.y, up.z * east.x - up.x * east.z, up.x * east.y - up.y * east.x);
    }
    double minimum = HUGE_VAL, maximum = -HUGE_VAL;
    for (unsigned z = 0; z < size; z++)
        for (unsigned x = 0; x < size; x++) {
            Sample *s = &samples[(size_t)z * size + x];
            DVec3 point = dv3(x * step - extent * .5, 0, z * step - extent * .5);
            if (earth_data) {
                PlanetGeo g = planet_geographic(
                    &planet, pd_add(origin, pd_add(pd_scale(east, point.x), pd_scale(north, point.z))));
                s->base = planet_measured_elevation(&planet, g.latitude_deg, g.longitude_deg);
                s->ground = planet_elevation_state(&planet, g.latitude_deg, g.longitude_deg, &s->state);
                double level, visible = s->ground;
                if (planet_water_elevation(&planet, g.latitude_deg, g.longitude_deg, &level))
                    visible = fmax(visible, level);
                DVec3 delta =
                    pd_sub(planet_from_geographic(&planet, g.latitude_deg, g.longitude_deg, visible), origin);
                s->vertex = dv3(pd_dot(delta, east), pd_dot(delta, up), pd_dot(delta, north));
            } else {
                s->base = generated(&config, biome, point, amplitude);
                double h_east = generated(&config, biome, pd_add(point, dv3(step, 0, 0)), amplitude),
                       h_west = generated(&config, biome, pd_add(point, dv3(-step, 0, 0)), amplitude),
                       h_north = generated(&config, biome, pd_add(point, dv3(0, 0, step)), amplitude),
                       h_south = generated(&config, biome, pd_add(point, dv3(0, 0, -step)), amplitude);
                LandscapeInput input = {.point_m = point,
                                        .latitude_deg = latitude,
                                        .height_m = s->base,
                                        .slope = hypot(h_east - h_west, h_north - h_south) / (2 * step),
                                        .source_spacing_m = step,
                                        .requested = biome,
                                        .wet = biome == BIOME_OCEAN || biome == BIOME_FRESHWATER,
                                        .marine = biome == BIOME_OCEAN};
                s->state = landscape_sample(&config, input, true);
                s->ground = s->base + s->state.detail_m;
                s->vertex = dv3(point.x, s->ground, point.z);
            }
            minimum = fmin(minimum, s->vertex.y);
            maximum = fmax(maximum, s->vertex.y);
        }
    bool ok = export_mesh(prefix, samples, (unsigned)size) &&
              export_samples(prefix, samples, (unsigned)size) &&
              export_image(prefix, samples, (unsigned)size);
    char path[2048];
    FILE *meta = ok ? output(prefix, "json", path) : NULL;
    if (meta) {
        fprintf(meta,
                "{\n  \"mode\": \"%s\",\n  \"size\": %lu,\n  \"spacing_mm\": %lu,\n  \"seed\": %u,\n"
                "  \"amplitude_m\": %.9g,\n  \"roughness\": %.9g,\n  \"moisture\": %.9g,\n  "
                "\"temperature_offset_k\": %.9g,\n"
                "  \"preset\": \"%s\",\n  \"latitude_deg\": %.9g,\n  \"longitude_deg\": %.9g,\n"
                "  \"origin_ecef_m\": [%.9f, %.9f, %.9f],\n  \"vertical_range_m\": [%.9f, %.9f],\n"
                "  \"note\": \"Procedural climate and geological estimates; no hydraulic erosion or "
                "photographic imagery.\"\n}\n",
                earth_data ? "engine-earth" : "synthetic", size, spacing_mm, config.seed, amplitude,
                config.roughness_scale, config.moisture_scale, config.temperature_offset_k,
                earth_data ? "auto" : biome_name(biome), latitude, longitude, origin.x, origin.y, origin.z,
                minimum, maximum);
        if (ferror(meta))
            ok = false;
        if (fclose(meta))
            ok = false;
    } else
        ok = false;
    free(samples);
    planet_destroy(&planet);
    if (ok)
        printf("Generated %lux%lu %s terrain, %.3f m across, %.3f..%.3f m vertical range; "
               "%s.{ply,csv,ppm,json}\n",
               size, size, earth_data ? "engine Earth" : biome_name(biome), extent, minimum, maximum, prefix);
    else
        fprintf(stderr, "Could not write landscape outputs for %s\n", prefix);
    return ok ? 0 : 1;
invalid:
    fputs("Invalid generation options; use --help\n", stderr);
    return 1;
}
