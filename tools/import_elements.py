#!/usr/bin/env python3
"""Generate the offline C element catalogue from a PubChem periodic-table snapshot."""
import argparse
import hashlib
import json
import math
import re
from pathlib import Path
import urllib.request

URL = "https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/JSON"
ROOT = Path(__file__).resolve().parents[1]


def generate(snapshot):
    table = json.loads(snapshot)["Table"]
    columns = table["Columns"]["Column"]
    rows = [dict(zip(columns, row["Cell"])) for row in table["Row"]]
    if len(rows) != 118 or [int(r["AtomicNumber"]) for r in rows] != list(range(1, 119)):
        raise ValueError("Expected 118 elements in atomic-number order")
    if len({r["Symbol"] for r in rows}) != 118:
        raise ValueError("Duplicate element symbol")
    header = ["/* Generated by tools/import_elements.py; IDs are atomic number minus one. */",
              "#ifndef ELEMENT_IDS_H", "#define ELEMENT_IDS_H", "typedef enum {"]
    entries = ["/* PubChem periodic table; source values, not a pressure-dependent phase model.",
               f"   Snapshot SHA256: {hashlib.sha256(snapshot).hexdigest()} */"]
    for row in rows:
        if not re.fullmatch(r"[A-Z][a-z]?", row["Symbol"]):
            raise ValueError("Invalid element symbol")
        name = "E_" + row["Symbol"].upper()
        number = int(row["AtomicNumber"])
        header.append(f"    {name} = {number - 1},")
        state = row["StandardState"]
        phase = "PHASE_" + state.rsplit(" ", 1)[-1].upper()
        if phase not in ("PHASE_SOLID", "PHASE_LIQUID", "PHASE_GAS"):
            raise ValueError(f"Unknown source phase: {state}")
        def value(key, multiplier=1):
            if not row[key]:
                return "NAN"
            number = float(row[key]) * multiplier
            if not math.isfinite(number) or number <= 0:
                raise ValueError(f"Invalid {key} for {row['Symbol']}")
            return format(number, ".12g")
        fields = [str(number), json.dumps(row["Symbol"]), json.dumps(row["Name"]),
                  value("AtomicMass"), value("Density", 1000), value("MeltingPoint"),
                  value("BoilingPoint"), phase,
                  "true" if state.startswith("Expected") else "false",
                  json.dumps(row["GroupBlock"])]
        entries.append(f"[{name}] = {{" + ", ".join(fields) + "},")
    header += ["    E_COUNT = 118", "} ElementId;", "#endif", ""]
    return "\n".join(header), "\n".join(entries) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "data/elements/pubchem.json")
    parser.add_argument("--output", type=Path, default=ROOT / "src")
    parser.add_argument("--download", action="store_true", help="explicitly refresh the source snapshot")
    parser.add_argument("--check", action="store_true", help="verify generated files without writing")
    args = parser.parse_args()
    if args.download:
        with urllib.request.urlopen(URL, timeout=60) as response:
            raw = response.read(2 * 1024 * 1024)
        generate(raw)  # Validate before replacing the offline snapshot.
        args.input.parent.mkdir(parents=True, exist_ok=True)
        args.input.write_bytes(raw)
    raw = args.input.read_bytes()
    header, entries = generate(raw)
    for name, text in (("element_ids.h", header), ("elements.inc", entries)):
        path = args.output / name
        if args.check:
            if path.read_text() != text:
                raise SystemExit(f"Stale generated file: {path}")
        else:
            path.write_text(text)
    print("Verified 118 PubChem elements" if args.check else "Generated 118 PubChem elements")


if __name__ == "__main__":
    main()
