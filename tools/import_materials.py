#!/usr/bin/env python3
"""Generate stable material IDs, C recipes and GLSL palette size from offline data."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ELEMENT_FIRST = 60  # Permanent reserved range: elemental IDs 60 through 177.
LEGACY = ['AIR','SOIL','GRASS','STONE','SAND','IRON','COPPER','WOOD','CLAY','WATER','ICE']

def generate():
    table = json.loads((ROOT/'data/elements/pubchem.json').read_text())['Table']
    columns = table['Columns']['Column']
    elements = [dict(zip(columns,r['Cell'])) for r in table['Row']]
    masses = {e['Symbol']:float(e['AtomicMass']) for e in elements}
    records = json.loads((ROOT/'data/materials/recipes.json').read_text())['materials']
    if [r['key'] for r in records[:11]] != LEGACY or any(r['id'] != i for i,r in enumerate(records[:11])):
        raise ValueError('Material IDs/legacy order differ')
    if len(elements) != 118 or [int(e['AtomicNumber']) for e in elements] != list(range(1,119)):
        raise ValueError('Invalid element identity order')
    saved_ids = [r['id'] for r in records] + list(range(ELEMENT_FIRST,ELEMENT_FIRST+118))
    if len(set(saved_ids)) != len(saved_ids) or sorted(saved_ids) != list(range(len(saved_ids))):
        raise ValueError('Material IDs must be unique and append after the reserved elemental range')
    index={r['key']:r for r in records}
    if len(index)!=len(records): raise ValueError('Duplicate recipe key')
    cache={}
    def recipe(key,path=()):
        if key in cache: return cache[key]
        if key in path: raise ValueError('Cyclic mineral mixture')
        source=index[key]['recipe']; result={}
        if 'mix' in source:
            for part,weight in source['mix'].items():
                if not math.isfinite(weight) or weight<0: raise ValueError('Invalid mixture weight')
                for symbol,value in recipe(part,path+(key,)).items():
                    result[symbol]=result.get(symbol,0)+weight*value
        else:
            atomic='atoms' in source
            for symbol,value in source['atoms' if atomic else 'fractions'].items():
                if symbol not in masses or not math.isfinite(value) or value<0:
                    raise ValueError('Invalid elemental recipe')
                result[symbol]=result.get(symbol,0)+value*(masses[symbol] if atomic else 1)
        total=sum(result.values())
        if not total>0 or not math.isfinite(total) or len(result)>16: raise ValueError('Invalid recipe size/mass')
        cache[key]={symbol:value/total for symbol,value in result.items() if value>0}
        return cache[key]
    ids=['/* Generated by tools/import_materials.py. Never reorder saved IDs. */',
         '#ifndef MATERIAL_IDS_H','#define MATERIAL_IDS_H','typedef enum {']
    entries=['/* Generated representative presets; see data/materials/recipes.json. */']
    def number(n):
        if n is None: return 'NAN'
        if not math.isfinite(n) or n<=0: raise ValueError('Invalid positive property')
        return format(n,'.10g')
    def entry(key,name,color,density,heat,conduct,family,phase,natural,estimated,parts,pure=-1):
        if len(color)!=3 or any(not math.isfinite(c) or not 0<=c<=1 for c in color):
            raise ValueError('Invalid color')
        composition=', '.join('{E_'+s.upper()+', '+format(v,'.10g')+'f}' for s,v in parts.items())
        # C requires a decimal point or exponent before the f suffix.
        import re
        composition=re.sub(r'(?<![.\w])([01])f\}',r'\1.0f}',composition)
        return f'''[MAT_{key}] = {{.name={json.dumps(name)}, .color={{ {', '.join(format(c,'.8g') for c in color)} }},
    .density_kg_m3={number(density)}, .specific_heat_j_kg_k={number(heat)}, .conductivity_w_m_k={number(conduct)},
    .solid={'true' if phase=='solid' else 'false'}, .constituent_count={len(parts)}, .composition={{ {composition} }},
    .family=FAMILY_{family.upper()}, .reference_phase=PHASE_{phase.upper()},
    .natural_surface={'true' if natural else 'false'}, .properties_estimated={'true' if estimated else 'false'}, .pure_element={pure}}},'''
    for record in records:
        key=record['key']; ids.append(f"    MAT_{key} = {record['id']},")
        pure='E_FE' if key=='IRON' else 'E_CU' if key=='COPPER' else '-1'
        entries.append(entry(key,record['name'],record['color'],record['density'],record['heat'],
            record['conductivity'],record['family'],record['phase'],record['natural'],record['estimated'],recipe(key),pure))
    first=ELEMENT_FIRST
    ids.append(f'    MAT_ELEMENT_FIRST = {first},')
    for i,e in enumerate(elements):
        symbol=e['Symbol']; key='ELEMENT_'+symbol.upper()
        ids.append(f'    MAT_{key} = {first+i},')
        colorhex=(e['CPKHexColor'] or 'A6A6A6').zfill(6)
        color=[int(colorhex[j:j+2],16)/255 for j in (0,2,4)]
        density=float(e['Density'])*1000 if e['Density'] else None
        heat={'Fe':449,'Cu':385}.get(symbol)
        conduct={'Fe':80.4,'Cu':401}.get(symbol)
        phase=e['StandardState'].split()[-1].lower()
        entries.append(entry(key,e['Name']+' (element)',color,density,heat,conduct,'element',phase,
                             False,False,{symbol:1},'E_'+symbol.upper()))
    count=len(saved_ids)
    if count>256: raise ValueError('PTEX palette uses byte IDs; widen before exceeding 256')
    ids += [f'    MAT_COUNT = {count}','} MaterialId;','#endif','']
    return {'src/material_ids.h':'\n'.join(ids), 'src/materials.inc':'\n'.join(entries)+'\n',
            'shaders/material_ids.glsl':f'// Generated by tools/import_materials.py\n#define MATERIAL_COUNT {count}\n'}

def main():
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for relative,contents in generate().items():
        path=ROOT/relative
        if args.check:
            if path.read_text()!=contents: raise SystemExit('Stale generated file: '+relative)
        else: path.write_text(contents)
    print('Verified material recipes and shader palette' if args.check else 'Generated material recipes and shader palette')
if __name__=='__main__': main()
